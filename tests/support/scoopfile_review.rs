fn repo(f: &Fixture) -> PathBuf {
    let path = f.temp.path().join("repo");
    fs::create_dir_all(path.join("bucket")).unwrap();
    fs::copy(f.manifest(), path.join("bucket/hello.json")).unwrap();
    git(&path, &["init", "-q"]).unwrap();
    git(&path, &["config", "user.name", "Fixture"]).unwrap();
    git(&path, &["config", "user.email", "fixture@example.org"]).unwrap();
    git(&path, &["add", "."]).unwrap();
    git(&path, &["commit", "-qm", "one"]).unwrap();
    path
}
fn combined(o: &Output) -> String {
    format!(
        "{}{}",
        String::from_utf8_lossy(&o.stdout),
        String::from_utf8_lossy(&o.stderr)
    )
}
#[test]
fn release_channel_config_is_excluded_and_refused_while_apps_continue() {
    let f = Fixture::new();
    let manifest = f.manifest();
    f.ok(
        "a",
        &["config", "release_catalog", "/trusted-local/catalog.json"],
    );
    f.ok("a", &["config", "main_bucket_url", "/trusted-local/main"]);
    let exported: Value = serde_json::from_str(&f.ok("a", &["export", "-c"])).unwrap();
    assert!(exported["config"].get("release_catalog").is_none());
    assert!(exported["config"].get("main_bucket_url").is_none());
    let path=f.document(json!({"config":{"release_catalog":"https://attacker.example/catalog.json","main_bucket_url":"https://attacker.example/main"},"apps":[{"Name":"hello","Source":manifest}]}));
    let o = f.cli("a").args(["import", &path]).output().unwrap();
    assert!(!o.status.success());
    assert!(combined(&o).contains("machine-specific config is not imported: release_catalog"));
    assert!(combined(&o).contains("machine-specific config is not imported: main_bucket_url"));
    assert!(f.temp.path().join("a/root/bin/hello").is_file());
    assert_eq!(
        f.ok("a", &["config", "release_catalog"]),
        "/trusted-local/catalog.json\n"
    );
    assert_eq!(
        f.ok("a", &["config", "main_bucket_url"]),
        "/trusted-local/main\n"
    );
}
